using Anarchy.Toolkit.Build.Cli.Core.Entity;
using Anarchy.Toolkit.Build.Cli.Infrastructure.Helper;
using System.Text;
using System.Text.RegularExpressions;

namespace Anarchy.Toolkit.Build.Cli.Core.Service;

/// <summary>
/// Keeps a solution's agent skills in step with its Makefiles: Make targets marked with <c>#@</c> must be listed by an
/// agent skill, whose commands section is generated from the targets' <c>#?</c>, <c>#+</c> and <c>#!</c> comments,
/// while the rest of the skill is written by people or agents.
/// </summary>
/// <remarks>
/// <para>
/// A <c>#@ skill-name</c> line before the first target of a <c>.mk</c> file assigns all its documented targets to that
/// skill; one right after a target (with its <c>#+</c> and <c>#!</c> lines) assigns only that target, and
/// <c>#@ -</c> exempts it. A bare <c>#@</c> names the skill <c>&lt;prefix&gt;-&lt;file&gt;</c>.
/// </para>
/// <para>
/// Skills follow the Agent Skills format (<c>&lt;directory&gt;/&lt;name&gt;/SKILL.md</c> with <c>name</c> and
/// <c>description</c> front matter) and must keep the <see cref="RequiredHeadings"/>. The commands are written between
/// <see cref="CommandsBegin"/> and <see cref="CommandsEnd"/>; <see cref="Sync"/> rewrites only that block.
/// </para>
/// </remarks>
/// <example>
/// <code language="csharp">
/// var actions = AgentSkillTasks.ReadMakeTargets(root, "shop");
/// string[] directories = [Path.Combine(root, AgentSkillTasks.DefaultDirectory)];
/// AgentSkillTasks.Sync(directories, actions);
/// var errors = AgentSkillTasks.Validate(directories, actions);
/// </code>
/// </example>
public static partial class AgentSkillTasks
{
    /// <summary>
    /// Where skills are installed and created, relative to the solution root.
    /// </summary>
    public const string DefaultDirectory = ".agents/skills";

    /// <summary>
    /// The line opening the generated commands block.
    /// </summary>
    public const string CommandsBegin = "<!-- anarchy:commands:begin (generated by 'make skills_sync' from the Makefiles' #? comments) -->";

    /// <summary>
    /// The line closing the generated commands block.
    /// </summary>
    public const string CommandsEnd = "<!-- anarchy:commands:end -->";

    /// <summary>
    /// The headings every skill listing commands must keep.
    /// </summary>
    public static IReadOnlyList<string> RequiredHeadings { get; } = ["## When to use", "## Commands"];

    private const string SkillFile = "SKILL.md";
    private const string Placeholder = "TODO";
    private const int MaxNameLength = 64;
    private const int MaxDescriptionLength = 1024;
    private static readonly string[] SkippedDirectories =
        ["bin", "obj", ".git", "node_modules", "artifacts", "vendor", "_site", ".fallout", "TestResults"];

    /// <summary>
    /// Reads the documented targets of every <c>.mk</c> file under <paramref name="root"/>, skipping build outputs,
    /// dependencies and symbolic links. A target declared in several files is read from the first, by path.
    /// </summary>
    /// <param name="root">The solution root.</param>
    /// <param name="prefix">The prefix of skills named by a bare <c>#@</c>; see <see cref="ToSkillName"/>.</param>
    /// <returns>The targets.</returns>
    public static IReadOnlyList<AgentAction> ReadMakeTargets(string root, string prefix) =>
        EnumerateFiles(Path.GetFullPath(root), "*.mk")
            .Order(StringComparer.Ordinal)
            .SelectMany(path => ParseMakeTargets(File.ReadAllText(path), Path.GetFileNameWithoutExtension(path), prefix))
            .DistinctBy(action => action.Name, StringComparer.Ordinal)
            .ToArray();

    /// <summary>
    /// Parses the documented targets of a Makefile: <c>name [alias...]: [prerequisites] #? description</c>, followed by
    /// <c>#+ VARIABLE|type|description</c>, <c>#! warning</c> and <c>#@ skill</c> lines.
    /// </summary>
    /// <param name="content">The Makefile's text.</param>
    /// <param name="file">The file's name, without extension.</param>
    /// <param name="prefix">The prefix of skills named by a bare <c>#@</c>.</param>
    /// <returns>The targets in declaration order.</returns>
    public static IReadOnlyList<AgentAction> ParseMakeTargets(string content, string file, string prefix)
    {
        ArgumentNullException.ThrowIfNull(content);
        var actions = new List<AgentAction>();
        string? fileSkill = null;
        var lines = content.ReplaceLineEndings("\n").Split('\n');
        for (var index = 0; index < lines.Length; index++)
        {
            var match = MakeTargetPattern().Match(lines[index]);
            if (!match.Success)
            {
                if (actions.Count == 0 && SkillMarker(lines[index]) is { } marker) fileSkill = marker;
                continue;
            }

            var names = match.Groups["names"].Value.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            var parameters = new List<AgentActionParameter>();
            var warnings = new List<string>();
            var skill = fileSkill;
            for (var next = index + 1; next < lines.Length && lines[next].StartsWith('#'); next++)
            {
                if (lines[next].StartsWith("#+", StringComparison.Ordinal) &&
                    lines[next][2..].Trim().Split('|', 3) is [var name, var type, var description])
                    parameters.Add(new AgentActionParameter(name.Trim(), type.Trim(), description.Trim()));
                else if (lines[next].StartsWith("#!", StringComparison.Ordinal))
                    warnings.Add(lines[next][2..].Trim());
                else if (SkillMarker(lines[next]) is { } marker)
                    skill = marker;
            }

            actions.Add(new AgentAction(names[0], match.Groups["description"].Value.Trim(), file, ResolveSkill(skill, prefix, file)) {
                Aliases = names[1..],
                Parameters = parameters,
                Warnings = warnings
            });
        }
        return actions;
    }

    /// <summary>
    /// Checks the skills required by <paramref name="actions"/>: each must exist below <paramref name="directories"/>
    /// with valid front matter, a description without placeholders, the <see cref="RequiredHeadings"/> and an up-to-date
    /// commands block. Every skill found must also have valid front matter and a unique name.
    /// </summary>
    /// <remarks>
    /// Names must be lowercase letters, digits and single hyphens, up to 64 characters, matching their directory;
    /// descriptions are limited to 1024 characters. Symbolic links below the directories are not followed.
    /// </remarks>
    /// <param name="directories">The skill directories; missing ones are skipped.</param>
    /// <param name="actions">The targets, usually from <see cref="ReadMakeTargets"/>.</param>
    /// <returns>The problems found; empty when the skills are valid.</returns>
    public static IReadOnlyList<string> Validate(IEnumerable<string> directories, IEnumerable<AgentAction> actions)
    {
        ArgumentNullException.ThrowIfNull(actions);
        var errors = new List<string>();
        var skills = ReadSkills(directories, errors);
        foreach (var duplicate in skills.GroupBy(skill => skill.Name, StringComparer.Ordinal).Where(group => group.Count() > 1))
            errors.Add($"Skill name '{duplicate.Key}' is used by {string.Join(", ", duplicate.Select(skill => skill.Path))}");

        foreach (var group in actions.Where(action => action.Skill is not null).GroupBy(action => action.Skill!, StringComparer.Ordinal))
        {
            var skill = skills.FirstOrDefault(skill => skill.Name == group.Key);
            if (skill is null)
            {
                errors.Add($"No skill '{group.Key}' for {string.Join(", ", group.Select(action => "make " + action.Name))}; run 'make skills_sync'");
                continue;
            }
            if (skill.Description.Contains(Placeholder, StringComparison.Ordinal))
                errors.Add($"{skill.Path}: replace the {Placeholder} in the description with what the skill is for");
            foreach (var heading in RequiredHeadings.Where(heading => !HasHeading(skill.Content, heading)))
                errors.Add($"{skill.Path}: missing the '{heading}' section");
            if (ExtractCommands(skill.Content) is not { } block)
                errors.Add($"{skill.Path}: missing the commands block; run 'make skills_sync'");
            else if (block != RenderCommands(group))
                errors.Add($"{skill.Path}: the commands block is out of date; run 'make skills_sync'");
        }
        return errors;
    }

    /// <summary>
    /// Creates each skill required by <paramref name="actions"/> that does not exist yet, from a template, in the first
    /// of <paramref name="directories"/>, and rewrites the commands block of every required skill. Text outside the
    /// block is kept; a skill without the block gets it appended.
    /// </summary>
    /// <param name="directories">The skill directories; skills are created in the first.</param>
    /// <param name="actions">The targets, usually from <see cref="ReadMakeTargets"/>.</param>
    /// <param name="log">Receives progress messages; <see langword="null"/> discards them.</param>
    /// <returns>The skill files created or changed.</returns>
    /// <exception cref="ArgumentException">Thrown when no directory is given.</exception>
    public static IReadOnlyList<string> Sync(IReadOnlyList<string> directories, IEnumerable<AgentAction> actions, Action<string>? log = null)
    {
        ArgumentNullException.ThrowIfNull(directories);
        ArgumentNullException.ThrowIfNull(actions);
        if (directories.Count == 0) throw new ArgumentException("Supply at least one skill directory.", nameof(directories));
        var report = log ?? (_ => { });
        var skills = ReadSkills(directories, []);
        var written = new List<string>();
        foreach (var group in actions.Where(action => action.Skill is not null).GroupBy(action => action.Skill!, StringComparer.Ordinal))
        {
            var block = RenderCommands(group);
            var path = skills.FirstOrDefault(skill => skill.Name == group.Key)?.Path;
            if (path is null)
            {
                path = Path.Combine(Path.GetFullPath(directories[0]), group.Key, SkillFile);
                if (File.Exists(path))
                {
                    report($"Skipping {path}: fix its front matter first");
                    continue;
                }
                FileHelper.WriteNewText(path, RenderTemplate(group.Key, block));
                written.Add(path);
                report($"Created {path}; describe what it is for and when to use it");
                continue;
            }

            var content = File.ReadAllText(path).ReplaceLineEndings("\n");
            var updated = ReplaceCommands(content, block);
            if (updated == content) continue;
            File.WriteAllText(path, updated);
            written.Add(path);
            report($"Updated the commands of {path}");
        }
        return written;
    }

    /// <summary>
    /// Reads the skills below <paramref name="directories"/>, adding the invalid ones to <paramref name="errors"/>.
    /// </summary>
    /// <param name="directories">The skill directories; missing ones are skipped.</param>
    /// <param name="errors">Receives why skills are invalid.</param>
    /// <returns>The valid skills.</returns>
    public static IReadOnlyList<AgentSkill> ReadSkills(IEnumerable<string> directories, ICollection<string> errors)
    {
        ArgumentNullException.ThrowIfNull(directories);
        ArgumentNullException.ThrowIfNull(errors);
        var skills = new List<AgentSkill>();
        var files = directories.Select(Path.GetFullPath).Where(Directory.Exists)
            .SelectMany(directory => EnumerateFiles(directory, SkillFile, skip: false))
            .Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal);
        foreach (var path in files)
        {
            if (ParseSkill(path, File.ReadAllText(path)) is not { } skill)
            {
                errors.Add($"{path}: missing front matter with a name and a description");
                continue;
            }

            var directory = Path.GetFileName(Path.GetDirectoryName(path));
            var problem = !SkillNamePattern().IsMatch(skill.Name) || skill.Name.Length > MaxNameLength
                ? $"name '{skill.Name}' must be lowercase letters, digits and single hyphens, up to {MaxNameLength} characters"
                : skill.Name != directory ? $"name '{skill.Name}' must match its directory '{directory}'"
                : skill.Description.Length > MaxDescriptionLength ? $"description is longer than {MaxDescriptionLength} characters"
                : null;
            if (problem is null) skills.Add(skill);
            else errors.Add($"{path}: {problem}");
        }
        return skills;
    }

    /// <summary>
    /// Parses a skill's <c>name</c> and <c>description</c> front matter.
    /// </summary>
    /// <param name="path">The <c>SKILL.md</c> path, recorded in the result.</param>
    /// <param name="content">The file's text.</param>
    /// <returns>The skill, or <see langword="null"/> without front matter, a name or a description.</returns>
    public static AgentSkill? ParseSkill(string path, string content)
    {
        ArgumentNullException.ThrowIfNull(content);
        var lines = content.ReplaceLineEndings("\n").Split('\n');
        if (lines is not ["---", ..]) return null;
        var end = Array.IndexOf(lines, "---", 1);
        if (end < 0) return null;

        var values = lines[1..end].Select(line => FrontMatterPattern().Match(line)).Where(match => match.Success)
            .GroupBy(match => match.Groups["key"].Value, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => Unquote(group.First().Groups["value"].Value), StringComparer.Ordinal);
        return values.TryGetValue("name", out var name) && values.TryGetValue("description", out var description) &&
               !string.IsNullOrWhiteSpace(name) && !string.IsNullOrWhiteSpace(description)
            ? new AgentSkill(path, name, description, content.ReplaceLineEndings("\n"))
            : null;
    }

    /// <summary>
    /// Renders the commands block for <paramref name="actions"/>, markers included: a table of each target with its
    /// aliases, description, warnings and parameters.
    /// </summary>
    /// <param name="actions">The targets of one skill, in order.</param>
    /// <returns>The block, ending with a newline.</returns>
    public static string RenderCommands(IEnumerable<AgentAction> actions)
    {
        ArgumentNullException.ThrowIfNull(actions);
        var text = new StringBuilder().Append(CommandsBegin).Append('\n')
            .Append("| Command | What it does | Parameters |\n|---|---|---|\n");
        foreach (var action in actions)
        {
            var command = string.Join(" or ", action.Aliases.Prepend(action.Name).Select(name => $"`make {name}`"));
            var description = Cell(action.Description) + string.Concat(action.Warnings.Select(warning => $" **Warning:** {Cell(warning)}"));
            var parameters = string.Join("<br>", action.Parameters.Select(parameter =>
                $"`{parameter.Name}` ({parameter.Type}): {Cell(parameter.Description)}"));
            text.Append($"| {command} | {description} | {parameters} |\n");
        }
        return text.Append(CommandsEnd).Append('\n').ToString();
    }

    /// <summary>
    /// Turns a name into a skill name segment: lowercase letters and digits joined by single hyphens, splitting
    /// PascalCase words (<c>Anarchy.Toolkit</c> becomes <c>anarchy-toolkit</c>, <c>mock-server</c> stays).
    /// </summary>
    /// <param name="value">The name to convert.</param>
    /// <returns>The skill name segment; empty when <paramref name="value"/> has no letters or digits.</returns>
    public static string ToSkillName(string value)
    {
        ArgumentNullException.ThrowIfNull(value);
        var words = WordBoundaryPattern().Replace(value, "$1-$2");
        return string.Join('-', NonAlphanumericPattern().Split(words.ToLowerInvariant()).Where(part => part.Length > 0));
    }

    private static string? SkillMarker(string line) => line.StartsWith("#@", StringComparison.Ordinal) ? line[2..].Trim() : null;

    private static string? ResolveSkill(string? marker, string prefix, string file) => marker switch {
        null or "-" => null,
        "" => $"{ToSkillName(prefix)}-{ToSkillName(file)}",
        _ => marker
    };

    private static bool HasHeading(string content, string heading) =>
        content.Split('\n').Any(line => line.TrimEnd() == heading);

    private static string? ExtractCommands(string content)
    {
        var begin = content.IndexOf(CommandsBegin, StringComparison.Ordinal);
        var end = content.IndexOf(CommandsEnd, StringComparison.Ordinal);
        return begin < 0 || end < begin ? null : content[begin..(end + CommandsEnd.Length)] + "\n";
    }

    private static string ReplaceCommands(string content, string block)
    {
        var begin = content.IndexOf(CommandsBegin, StringComparison.Ordinal);
        var end = content.IndexOf(CommandsEnd, StringComparison.Ordinal);
        if (begin < 0 || end < begin) return content.TrimEnd('\n') + "\n\n## Commands\n\n" + block;
        var after = content[(end + CommandsEnd.Length)..];
        return content[..begin] + block + (after.StartsWith('\n') ? after[1..] : after);
    }

    private static string RenderTemplate(string name, string block) => $"""
        ---
        name: {name}
        description: "{Placeholder}: what these operations are for, and when an agent should use this skill."
        ---

        # {name}

        <!-- Explain the workflow: what to run first, what to check afterwards, what to avoid. Everything outside the
             commands block is yours: 'make skills_sync' only rewrites the block. -->

        ## When to use

        - {Placeholder}

        ## Commands

        Run them from the solution root; `make help COMMAND=<target>` describes one.

        {block}
        """.ReplaceLineEndings("\n");

    private static IEnumerable<string> EnumerateFiles(string directory, string pattern, bool skip = true)
    {
        var pending = new Stack<string>([directory]);
        while (pending.TryPop(out var current))
        {
            foreach (var file in Directory.EnumerateFiles(current, pattern)) yield return file;
            foreach (var child in Directory.EnumerateDirectories(current))
            {
                if (new DirectoryInfo(child).LinkTarget is not null) continue;
                if (skip && SkippedDirectories.Contains(Path.GetFileName(child), StringComparer.Ordinal)) continue;
                pending.Push(child);
            }
        }
    }

    private static string Unquote(string value)
    {
        value = value.Trim();
        if (value.Length >= 2 && value[0] == '"' && value[^1] == '"')
            return value[1..^1].Replace("\\\"", "\"", StringComparison.Ordinal).Replace("\\\\", "\\", StringComparison.Ordinal);
        if (value.Length >= 2 && value[0] == '\'' && value[^1] == '\'')
            return value[1..^1].Replace("''", "'", StringComparison.Ordinal);
        return value;
    }

    private static string Cell(string value) => value.Replace("|", "\\|", StringComparison.Ordinal);

    [GeneratedRegex(@"^(?<names>[A-Za-z0-9_][A-Za-z0-9_\- ]*?)\s*:(?![:=])[^#]*#\?\s*(?<description>.*)$")]
    private static partial Regex MakeTargetPattern();

    [GeneratedRegex(@"^(?<key>[A-Za-z0-9_-]+):\s*(?<value>.*)$")]
    private static partial Regex FrontMatterPattern();

    [GeneratedRegex("^[a-z0-9]+(-[a-z0-9]+)*$")]
    private static partial Regex SkillNamePattern();

    [GeneratedRegex("([a-z0-9])([A-Z])")]
    private static partial Regex WordBoundaryPattern();

    [GeneratedRegex("[^a-z0-9]+")]
    private static partial Regex NonAlphanumericPattern();
}
