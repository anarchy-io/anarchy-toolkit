CREATE TABLE type_registry (
    id NUMBER(9) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(200) NOT NULL UNIQUE
);

CREATE TABLE test_order (
    id NUMBER(18) PRIMARY KEY,
    sku VARCHAR2(100) NOT NULL
);

CREATE TABLE domain_event (
    id NUMBER(18) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_aggregate_id NUMBER(9) NOT NULL REFERENCES type_registry(id),
    aggregate_id VARCHAR2(100) NOT NULL,
    type_event_id NUMBER(9) NOT NULL REFERENCES type_registry(id),
    payload JSON,
    custom_attributes JSON,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (type_aggregate_id, aggregate_id, type_event_id)
);

CREATE TABLE it_order (id NUMBER(9) PRIMARY KEY);
CREATE TABLE it_stock (id NUMBER(9) PRIMARY KEY);
CREATE TABLE it_event (id NUMBER(9) PRIMARY KEY);

CREATE TABLE it_outbox (
    id NUMBER(9) PRIMARY KEY,
    published NUMBER(1) DEFAULT 0 NOT NULL,
    age_days NUMBER(9) DEFAULT 0 NOT NULL
);
